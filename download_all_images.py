def main():
    output_dir = os.path.join(os.getcwd(), 'images')
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
        print(f"Created output directory: {output_dir}")

    total = len(FILE_IDS)
    print(f"Starting download of {total} images...")
    
    # We can pre-scan existing filenames in the images folder to skip files if we already know they are there.
    # However, since we don't know the mapping from File ID to Filename without making a request,
    # let's download everything. gdown is smart and skips or overrides fast if the connection is good.
    # To be extremely helpful, if a download fails we catch it and proceed.
    success_count = 0
    for idx, file_id in enumerate(FILE_IDS):
        print(f"\n[{idx + 1} / {total}] Downloading ID: {file_id} ...")
        try:
            # We specify the output directory, and gdown handles auto-naming based on Google Drive metadata
            output_path = gdown.download(id=file_id, output=os.path.join(output_dir, ''), quiet=True)
            if output_path:
                print(f"-> Success: {os.path.basename(output_path)}")
                success_count += 1
            else:
                print("-> Failed: No file path returned")
        except Exception as e:
            print(f"-> Error downloading {file_id}: {e}")

    print(f"\nDownload session finished! {success_count} / {total} files processed successfully.")

if __name__ == '__main__':
    main()
